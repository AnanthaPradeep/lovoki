"""Generates supabase/migrations/20261104000100_places_seed.sql from GeoNames (CC-BY 4.0, https://www.geonames.org).
Download cities15000.zip, admin1CodesASCII.txt and countryInfo.txt from https://download.geonames.org/export/dump/ into one folder and run:
    python scripts/build-places-seed.py <folder> [min_population=100000]
The migration is committed; this script only exists so the seed can be rebuilt (for example with a lower population threshold)."""
import os, sys, zipfile, io

folder = sys.argv[1]; minpop = int(sys.argv[2]) if len(sys.argv) > 2 else 100000
admin1 = {}
for l in open(os.path.join(folder, 'admin1CodesASCII.txt'), encoding='utf-8'):
    code, name, *_ = l.rstrip('\n').split('\t'); admin1[code] = name
country = {}
for l in open(os.path.join(folder, 'countryInfo.txt'), encoding='utf-8'):
    if l.startswith('#') or not l.strip(): continue
    f = l.rstrip('\n').split('\t'); country[f[0]] = f[4]
rows = []
with zipfile.ZipFile(os.path.join(folder, 'cities15000.zip')) as z:
    for l in io.TextIOWrapper(z.open('cities15000.txt'), encoding='utf-8'):
        f = l.rstrip('\n').split('\t'); pop = int(f[14])
        if pop < minpop: continue
        rows.append((int(f[0]), f[1], admin1.get(f'{f[8]}.{f[10]}', ''), f[8], country.get(f[8], f[8]), round(float(f[4]), 3), round(float(f[5]), 3), pop))
rows.sort()
q = lambda s: "'" + s.replace("'", "''") + "'"
out = ['-- GENERATED by scripts/build-places-seed.py. Data: GeoNames (https://www.geonames.org), licensed CC-BY 4.0. See docs/ATTRIBUTION.md.',
       f'-- {len(rows)} places with population >= {minpop}. Coordinates here are the city centre; profiles store only a coarser grid (see the Phase 3.5 migration).', 'begin;']
for i in range(0, len(rows), 400):
    out.append('insert into public.places (id, name, region, country_code, country, lat, lng, population) values')
    out.append(',\n'.join(f'({r[0]}, {q(r[1])}, {q(r[2])}, {q(r[3])}, {q(r[4])}, {r[5]}, {r[6]}, {r[7]})' for r in rows[i:i + 400]) + '\non conflict (id) do nothing;')
out.append('commit;')
open('supabase/migrations/20261104000100_places_seed.sql', 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print(len(rows), 'places')
